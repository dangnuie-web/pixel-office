'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('PODesktop', {
  platform: process.platform,
  publicEdition: process.env.PO_PUBLIC === '1',
  kind: (p) => ipcRenderer.invoke('po:kind', p),
  read: (p) => ipcRenderer.invoke('po:read', p),
  list: (p) => ipcRenderer.invoke('po:list', p),
  readBytes: (p, max) => ipcRenderer.invoke('po:read-bytes', p, max),
  write: (p, t, o) => ipcRenderer.invoke('po:write', p, t, o && o.newOnly ? { newOnly: true } : undefined),
  append: (p, t) => ipcRenderer.invoke('po:append', p, t),
  move: (a, b) => ipcRenderer.invoke('po:move', a, b),
  trash: (p) => ipcRenderer.invoke('po:trash', p),
  toolList: () => ipcRenderer.invoke('po:tool-list'),
  toolStart: (id, params) => ipcRenderer.invoke('po:tool-start', id, params),
  toolStop: (id) => ipcRenderer.invoke('po:tool-stop', id),
  toolServer: () => ipcRenderer.invoke('po:tool-server'),
  toolOffice: () => ipcRenderer.invoke('po:tool-office'),
  toolOpenPortfolio: () => ipcRenderer.invoke('po:tool-open-portfolio'),
  toolOpen: (rel) => ipcRenderer.invoke('po:tool-open', rel),
  toolReveal: (rel) => ipcRenderer.invoke('po:tool-reveal', rel),
  toolCopy: (t) => ipcRenderer.invoke('po:tool-copy', t),
  toolPickMd: () => ipcRenderer.invoke('po:tool-pick-md'),
  toolPickDir: (startRel) => ipcRenderer.invoke('po:tool-pick-dir', startRel),
  toolRunJson: (id, params) => ipcRenderer.invoke('po:tool-run-json', id, params),
  pickImage: () => ipcRenderer.invoke('po:pick-image'),
  acceptDrop: (file) => { let p = ''; try { p = webUtils.getPathForFile(file); } catch (e) { p = ''; } return ipcRenderer.invoke('po:accept-image', p); },
  officeGet: () => ipcRenderer.invoke('po:office-get'),
  officePick: () => ipcRenderer.invoke('po:office-pick'),
  copy: (t) => ipcRenderer.invoke('po:copy', String(t == null ? '' : t)),
  officeOpen: () => ipcRenderer.invoke('po:office-open'),
  bossSave: (name) => ipcRenderer.invoke('po:boss-save', String(name == null ? '' : name)),
  officePickParent: (o) => ipcRenderer.invoke('po:office-pick-parent', o && o.peek ? { peek: true } : undefined),
  makeOffice: (input) => ipcRenderer.invoke('po:make-office', input),
  staffState: () => ipcRenderer.invoke('po:staff-state'),
  staffHire: (o) => ipcRenderer.invoke('po:staff-hire', { id: String(o && o.id || ''), name: String(o && o.name || '') }),
  staffFire: (o) => ipcRenderer.invoke('po:staff-fire', { id: String(o && o.id || '') }),
  guideReplant: () => ipcRenderer.invoke('po:guide-replant'),
  skillsList: () => ipcRenderer.invoke('po:skills-list'),
  staffRename: (o) => ipcRenderer.invoke('po:staff-rename', { id: String(o && o.id || ''), name: String(o && o.name || '') }),
  petInfo: () => ipcRenderer.invoke('po:pet-info'),
  petLaunch: () => ipcRenderer.invoke('po:pet-launch'),
  petGet: () => ipcRenderer.invoke('po:pet-get'),
  onRefreshKey: (cb) => { const f = () => cb(); ipcRenderer.on('po:refresh-key', f); return () => ipcRenderer.removeListener('po:refresh-key', f); },
  onTool: (cb) => { const f = (e, ev) => cb(ev); ipcRenderer.on('po:tool-event', f); return () => ipcRenderer.removeListener('po:tool-event', f); },
});
