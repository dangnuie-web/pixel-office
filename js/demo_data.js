  function splitParts(text) {
    const parts = { 로드맵: new Map(), 계획서: new Map() };
    let cur = null;
    String(text || '').split(/\r?\n/).forEach((l) => {
      const m = /^<!--\s*(로드맵|계획서)\s*:\s*(.+?)\s*-->\s*$/.exec(l.trim());
      if (m) { cur = [m[1], m[2]]; if (!parts[m[1]].has(m[2])) parts[m[1]].set(m[2], []); return; }
      if (cur) parts[cur[0]].get(cur[1]).push(l);
    });
    return parts;
  }
